"""Generate the native version lookup from the single reviewed JSON catalog."""

from pathlib import Path
import sys

sys.path[:0] = [str(Path(__file__).resolve().parents[2] / "src"), str(Path(__file__).resolve().parents[2])]

import argparse
import json

ROOT = Path(__file__).resolve().parents[2]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True, help="Generated header path")
    target = parser.parse_args().output
    data = json.loads((ROOT / "config/versions/profiles.json").read_text())
    rows = []
    for r in data["intervals"]:
        s = r["screen"]
        for v in r["versions"]:
            pre262 = int(s["reference_terrain_profile"] != "26.3")
            rows.append(f'{{"{v}",{pre262}}},')
    text = (
        "// Generated by scripts/build/versions.py\n#pragma once\nstruct HutVersionConfig {const char* name;bool pre262;};\nstatic constexpr HutVersionConfig hutVersionConfigs[]={\n"
        + "\n".join(rows)
        + "\n};\n"
    )
    target.parent.mkdir(parents=True, exist_ok=True)
    if not target.exists() or target.read_text() != text:
        target.write_text(text)


if __name__ == "__main__":
    main()
